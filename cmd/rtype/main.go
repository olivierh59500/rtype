// Command rtype runs the native Go port using locally extracted original assets.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"time"

	"github.com/hajimehoshi/ebiten/v2"
	"github.com/olivierh59500/r-type/internal/game"
	"github.com/olivierh59500/r-type/internal/pilot"
	"github.com/olivierh59500/r-type/internal/sim"
)

func main() {
	assets := flag.String("assets", "assets/runtime", "resources reconstructed from the original ADF")
	touch := flag.Bool("touch", false, "show touch controls; mouse can test each button")
	frames := flag.Int("frames", 0, "exit after this many ticks (zero means unlimited)")
	capture := flag.String("capture", "", "save the final frame as a local PNG")
	demo := flag.Bool("autoplay", false, "use deterministic input for a bounded visual check")
	muted := flag.Bool("mute", false, "silence this game's output while keeping its sound sequencers active")
	stage := flag.Int("stage", 1, "starting stage for a development check (1 through 8)")
	replayPath := flag.String("replay", "", "normal-input replay JSON generated by cmd/playcheck")
	attractEnabled := flag.Bool("attract", true, "show the expert first-stage demo after title inactivity")
	attractDelay := flag.Duration("attract-delay", 20*time.Second, "focused title inactivity before the expert demo")
	flag.Parse()
	var replay *pilot.Replay
	if *replayPath != "" {
		file, err := os.Open(*replayPath)
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		replay, err = pilot.ReadReplay(file)
		file.Close()
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		if *stage != 1 || *demo {
			fmt.Fprintln(os.Stderr, "replay requires the original stage-one title and manual input mode")
			os.Exit(2)
		}
		if *frames == 0 {
			*frames = len(replay.Frames)
		}
	}
	if *frames < 0 || *stage < 1 || *stage > 8 || (*capture != "" && *frames == 0) || *attractDelay <= 0 {
		fmt.Fprintln(os.Stderr, "invalid frame limit, capture, stage or attract delay")
		os.Exit(2)
	}
	g, err := game.New(*assets)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	g.SetMuted(*muted)
	g.SetTouchEnabled(*touch)
	if *attractEnabled {
		g.SetAttractDelay(max(1, int(*attractDelay/(time.Second/sim.TickRate))))
	} else {
		g.SetAttractDelay(0)
	}
	g.FrameLimit, g.CapturePath, g.AutoPlay = *frames, *capture, *demo
	if replay != nil {
		if err := g.SetReplay(replay); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
	if *stage != 1 {
		if err := g.World.StartStage(*stage); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
	if dir, err := os.UserConfigDir(); err == nil {
		g.SetDataDir(filepath.Join(dir, "r-type-go"))
	}
	ebiten.SetTPS(sim.TickRate)
	ebiten.SetWindowTitle("R-Type — Amiga Go Port")
	ebiten.SetWindowSize(960, 624)
	ebiten.SetWindowResizingMode(ebiten.WindowResizingModeEnabled)
	ebiten.SetScreenFilterEnabled(false)
	if err := ebiten.RunGame(g); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
